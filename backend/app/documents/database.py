"""One SQL repository boundary. SQLite is an explicit offline diagnostic profile."""
from contextlib import contextmanager
from pathlib import Path
import sqlite3

def schema_statements(dialect):
    company_id = "INTEGER PRIMARY KEY AUTOINCREMENT" if dialect == "sqlite" else "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    return [
        "CREATE TABLE IF NOT EXISTS t_company (id " + company_id + ",stock_code VARCHAR(16) UNIQUE NOT NULL,stock_name VARCHAR(128) NOT NULL,industry VARCHAR(128),market VARCHAR(32),created_at VARCHAR(40))",
        "CREATE TABLE IF NOT EXISTS t_document_schema (revision INTEGER PRIMARY KEY)",
        """CREATE TABLE IF NOT EXISTS t_document (
        id VARCHAR(36) PRIMARY KEY,corpus_type VARCHAR(20) NOT NULL CHECK(corpus_type IN ('annual_report','regulation')),
        company_id INTEGER REFERENCES t_company(id),report_year INTEGER,title TEXT NOT NULL,created_at VARCHAR(40) NOT NULL,
        CHECK((corpus_type='annual_report' AND company_id IS NOT NULL AND report_year IS NOT NULL) OR (corpus_type='regulation' AND company_id IS NULL AND report_year IS NULL)))""",
        "CREATE UNIQUE INDEX IF NOT EXISTS uq_annual_document ON t_document(company_id,report_year) WHERE corpus_type='annual_report'",
        """CREATE TABLE IF NOT EXISTS t_document_version (
        id VARCHAR(36) PRIMARY KEY,document_id VARCHAR(36) NOT NULL REFERENCES t_document(id),version_label TEXT NOT NULL,
        filename TEXT NOT NULL,storage_key TEXT NOT NULL,file_sha256 VARCHAR(64) NOT NULL,source_format VARCHAR(8) NOT NULL,
        metadata_json TEXT NOT NULL,created_at VARCHAR(40) NOT NULL,UNIQUE(document_id,file_sha256))""",
        """CREATE TABLE IF NOT EXISTS t_parse_run (
        id VARCHAR(36) PRIMARY KEY,version_id VARCHAR(36) NOT NULL REFERENCES t_document_version(id),
        status VARCHAR(16) NOT NULL,config_json TEXT NOT NULL,parser_identity TEXT NOT NULL,warnings_json TEXT NOT NULL,
        error_code TEXT,created_at VARCHAR(40) NOT NULL)""",
        """CREATE TABLE IF NOT EXISTS t_text_frame (
        id VARCHAR(36) PRIMARY KEY,parse_id VARCHAR(36) NOT NULL REFERENCES t_parse_run(id),ordinal INTEGER NOT NULL,
        physical_page INTEGER,text TEXT NOT NULL,text_sha256 VARCHAR(64) NOT NULL,text_origin TEXT NOT NULL,
        UNIQUE(parse_id,ordinal))""",
        """CREATE TABLE IF NOT EXISTS t_document_chunk (
        id VARCHAR(36) PRIMARY KEY,parse_id VARCHAR(36) NOT NULL REFERENCES t_parse_run(id),frame_id VARCHAR(36) NOT NULL REFERENCES t_text_frame(id),
        ordinal INTEGER NOT NULL,char_start INTEGER NOT NULL,char_end INTEGER NOT NULL,
        content TEXT NOT NULL,content_sha256 VARCHAR(64) NOT NULL,
        CHECK(char_start>=0 AND char_end>char_start),UNIQUE(parse_id,ordinal))""",
        """CREATE TABLE IF NOT EXISTS t_job (
        id VARCHAR(36) PRIMARY KEY,kind VARCHAR(16) NOT NULL,status VARCHAR(20) NOT NULL,payload_json TEXT NOT NULL,
        result_json TEXT,error_code TEXT,idempotency_key TEXT UNIQUE,request_sha256 VARCHAR(64) NOT NULL,
        lease_until VARCHAR(40),lease_owner VARCHAR(36),attempt_count INTEGER NOT NULL DEFAULT 0,
        created_at VARCHAR(40) NOT NULL,updated_at VARCHAR(40) NOT NULL)""",
        "CREATE INDEX IF NOT EXISTS ix_document_jobs ON t_job(status,lease_until,created_at)",
        """CREATE TABLE IF NOT EXISTS t_index_version (
        id VARCHAR(36) PRIMARY KEY,status VARCHAR(16) NOT NULL,profile VARCHAR(32) NOT NULL,
        config_json TEXT NOT NULL,manifest_key TEXT,manifest_sha256 VARCHAR(64),created_at VARCHAR(40) NOT NULL)""",
        """CREATE TABLE IF NOT EXISTS t_index_member (
        index_id VARCHAR(36) NOT NULL REFERENCES t_index_version(id),
        chunk_id VARCHAR(36) NOT NULL REFERENCES t_document_chunk(id),ordinal INTEGER NOT NULL,
        PRIMARY KEY(index_id,chunk_id),UNIQUE(index_id,ordinal))""",
    ]

class Session:
    def __init__(self, connection, dialect):
        self.connection, self.dialect = connection, dialect

    def execute(self, sql, params=()):
        cursor = self.connection.cursor()
        cursor.execute(sql if self.dialect == "sqlite" else sql.replace("?", "%s"), params)
        return cursor

    def rows(self, sql, params=()):
        cursor = self.execute(sql, params)
        names = [c[0] for c in cursor.description]
        return [dict(zip(names, row)) for row in cursor.fetchall()]

    def one(self, sql, params=()):
        rows = self.rows(sql, params)
        return rows[0] if rows else None

class Database:
    def __init__(self, url):
        self.url = url
        self.dialect = "sqlite" if url.startswith("sqlite:///") else "postgresql"
        self.engine = None
        if self.dialect == "sqlite":
            self.filename = Path(url[len("sqlite:///"):]).resolve()
            self.filename.parent.mkdir(parents=True, exist_ok=True)

    @contextmanager
    def session(self):
        if self.dialect == "sqlite":
            connection = sqlite3.connect(self.filename, timeout=30)
            connection.execute("PRAGMA foreign_keys=ON")
        else:
            if self.engine is None:
                from sqlalchemy import create_engine
                self.engine = create_engine(self.url, pool_pre_ping=True)
            connection = self.engine.raw_connection()
        try:
            yield Session(connection, self.dialect)
            connection.commit()
        except BaseException:
            connection.rollback()
            raise
        finally:
            connection.close()

    def migrate(self):
        with self.session() as session:
            for sql in schema_statements(self.dialect):
                session.execute(sql)
            session.execute("INSERT INTO t_document_schema(revision) VALUES(2) ON CONFLICT(revision) DO NOTHING")

    def ready(self):
        with self.session() as session:
            return session.one("SELECT revision FROM t_document_schema WHERE revision=2") is not None
