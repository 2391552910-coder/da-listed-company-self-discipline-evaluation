import { test, expect } from '@playwright/test'
test('visual shell, scene interaction and motion preference survive navigation', async ({page})=>{
 await page.goto('/')
 await expect(page.getByRole('heading',{level:1})).toContainText('从原文出发')
 await page.getByRole('tab',{name:'法规依据',exact:true}).click()
 await expect(page.getByRole('tabpanel')).toContainText('共享法规库')
 await page.getByRole('tab',{name:'法规依据',exact:true}).press('ArrowRight')
 await expect(page.getByRole('tabpanel')).toContainText('逐题保存回答')
 await page.getByRole('button',{name:'减少动效',exact:true}).click()
 await expect(page.locator('.app-layout')).toHaveAttribute('data-motion','reduced')
 await page.getByRole('menuitem',{name:'公司管理',exact:true}).click()
 await expect(page.getByRole('heading',{name:'公司管理',exact:true})).toBeVisible()
 await page.reload()
 await expect(page.locator('.app-layout')).toHaveAttribute('data-motion','reduced')
 await page.screenshot({path:'../test-results/browser-design-company.png',fullPage:true})
 await page.goto('/')
 await expect(page.getByRole('heading',{level:1})).toBeVisible()
 await page.screenshot({path:'../test-results/browser-design-overview.png',fullPage:true})
})
test('small screens and system reduced motion preserve usable content',async({page})=>{
 await page.setViewportSize({width:375,height:812})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('/')
 await expect(page.getByRole('heading',{level:1})).toBeVisible()
 await expect(page.getByRole('tab',{name:'评价结论',exact:true})).toBeVisible()
 expect(await page.locator('.hero-copy').evaluate(el=>getComputedStyle(el).animationName)).toBe('none')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await page.getByRole('tab',{name:'评价结论',exact:true}).click()
 await expect(page.getByRole('tabpanel')).toContainText('资料缺口')
 await page.screenshot({path:'../test-results/browser-design-mobile.png',fullPage:true})
})
