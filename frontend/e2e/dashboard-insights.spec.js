import { test, expect } from '@playwright/test'
test('live dashboard charts follow persisted counts and source selection',async({page})=>{
 await page.goto('/')
 const response=await page.request.get('/api/v1/dashboard')
 const data=(await response.json()).data
 const count=data.job_statuses.reduce((n,row)=>n+row.count,0)
 await expect(page.getByTestId('insights-task-total')).toHaveText(String(count))
 await expect(page.getByTestId('insights-demo-notice')).toHaveCount(0)
 await page.getByRole('button',{name:'年报入选',exact:true}).click()
 await expect(page.getByRole('button',{name:'年报入选',exact:true})).toHaveAttribute('aria-pressed','true')
 await expect(page.getByTestId('dashboard-insights')).toContainText('不代表语义支持')
 await page.screenshot({path:'../test-results/browser-insights-live.png',fullPage:true})
})
test('unavailable statistics stay unknown; explicit demo is labelled and responsive',async({page})=>{
 await page.route('**/api/v1/dashboard*',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'验收模拟：统计服务不可用'})}))
 await page.goto('/')
 await expect(page.getByTestId('insights-task-total')).toHaveText('—')
 await page.getByRole('button',{name:'预览图表样式',exact:true}).click()
 await expect(page.getByTestId('insights-demo-notice')).toContainText('演示数据')
 await expect(page.getByTestId('insights-task-total')).toHaveText('48')
 const bars=page.getByTestId('insights-coverage-bars')
 await expect(bars).toContainText('83%')
 await page.getByRole('button',{name:'年报入选',exact:true}).click()
 await expect(bars).toContainText('100%')
 await page.getByTestId('dashboard-insights').screenshot({path:'../test-results/browser-insights-panel.png'})
 await page.screenshot({path:'../test-results/browser-insights-demo.png',fullPage:true})
 await page.setViewportSize({width:375,height:812})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await expect(page.getByTestId('insights-demo-notice')).toBeVisible()
 await page.screenshot({path:'../test-results/browser-insights-mobile.png',fullPage:true})
 await page.getByRole('button',{name:'返回真实统计',exact:true}).click()
 await expect(page.getByTestId('insights-task-total')).toHaveText('—')
})
