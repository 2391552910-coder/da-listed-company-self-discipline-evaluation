import { test, expect } from '@playwright/test'
import fs from 'node:fs/promises'

// Real application and browser, synthetic sources and HTTP provider. This is
// workflow acceptance and does not establish model quality or legal support.
test('persistent evaluation, original evidence, and frozen HTML/PDF downloads', async ({ page }) => {
  await page.goto('/evaluations/new?stock_code=019997')
  await expect(page.getByRole('heading', { name: '评价工作台' })).toBeVisible()
  await page.getByTestId('evaluation-index').getByRole('combobox').click()
  await page.getByRole('option', { name: /bm25_diagnostic/ }).click()
  await page.getByTestId('evaluation-question').locator('textarea').fill('依据年报和规则，审计委员会履职有哪些可观察依据与限制？')
  await page.getByText('检索与法规时点', { exact: true }).click()
  await page.getByTestId('evaluation-tokenizer').getByRole('combobox').click()
  await page.getByRole('option', { name: 'UTF-8 字节诊断（不是 tokens）' }).click()
  await expect(page.getByTestId('evaluation-submit')).toBeEnabled()
  await page.getByTestId('evaluation-submit').click()
  await expect(page).toHaveURL(/\/evaluations\/[0-9a-f-]{36}$/)
  const detailUrl = page.url()
  await expect(page.getByTestId('detail-answer-text')).toContainText('浏览器验收合成回答')
  await expect(page.getByTestId('detail-answer-text')).toContainText('不构成研究结论')
  await page.reload()
  await expect(page.getByTestId('detail-answer-text')).toContainText('浏览器验收合成回答')
  await page.getByText(/论断与引用/).first().click()
  await page.getByTestId('citation-open').first().click()
  const dialog = page.getByRole('dialog', { name: '引用证据与来源核对' })
  await expect(dialog).toBeVisible()
  await expect(page.getByTestId('evidence-content')).toContainText('合成')
  await page.getByTestId('verify-source').click()
  await expect(page.getByTestId('source-status')).toContainText('校验通过')
  const sourceHref = await dialog.getByRole('link', { name: /打开原始文件/ }).getAttribute('href')
  const original = await page.request.get(sourceHref.split('#')[0])
  expect(original.ok()).toBeTruthy()
  expect(original.headers()['content-type']).toContain('pdf')
  expect((await original.body()).subarray(0, 4).toString()).toBe('%PDF')
  await dialog.getByRole('button', { name: /close/i }).click()
  await page.getByRole('button', { name: '报告导出', exact: true }).click()
  await expect(page).toHaveURL(/\/reports-export\?run_id=/)
  await page.getByTestId('report-create-html').click()
  await expect(page.getByTestId('report-download-html')).toBeVisible()
  const htmlPromise = page.waitForEvent('download')
  await page.getByTestId('report-download-html').click()
  const htmlDownload = await htmlPromise
  const html = await fs.readFile(await htmlDownload.path(), 'utf8')
  expect(html).toContain('浏览器验收合成回答')
  expect(html).toContain('第三章')
  expect(html).toContain('019997')
  await page.getByTestId('report-create-pdf').click()
  await expect(page.getByTestId('report-download-pdf')).toBeVisible()
  const pdfPromise = page.waitForEvent('download')
  await page.getByTestId('report-download-pdf').click()
  const pdfDownload = await pdfPromise
  const pdf = await fs.readFile(await pdfDownload.path())
  expect(pdf.subarray(0, 4).toString()).toBe('%PDF')
  expect(pdf.length).toBeGreaterThan(10000)
  await page.reload()
  await expect(page.getByTestId('report-download-html')).toBeVisible()
  await expect(page.getByTestId('report-download-pdf')).toBeVisible()
  await page.screenshot({ path: '../test-results/browser-report-exports.png', fullPage: true })
  await page.goto(detailUrl)
  await expect(page.getByTestId('detail-answer-text')).toContainText('浏览器验收合成回答')
})

test('four-dimension workspace preserves evidence gaps without numeric scores', async ({ page }) => {
  await page.goto('/evaluations/new?stock_code=019997')
  await page.getByTestId('evaluation-index').getByRole('combobox').click()
  await page.getByRole('option', { name: /bm25_diagnostic/ }).click()
  await page.getByText('完整四维', { exact: true }).click()
  await page.getByText('检索与法规时点', { exact: true }).click()
  await page.getByTestId('evaluation-tokenizer').getByRole('combobox').click()
  await page.getByRole('option', { name: 'UTF-8 字节诊断（不是 tokens）' }).click()
  await page.getByTestId('evaluation-submit').click()
  await expect(page).toHaveURL(/\/evaluations\/[0-9a-f-]{36}$/)
  await expect(page.getByTestId('detail-answer-text')).toHaveCount(4)
  for (const answer of await page.getByTestId('detail-answer-text').all()) {
    await expect(answer).toContainText('浏览器验收合成回答')
  }
  const dimensions = page.locator('.el-table__body-wrapper').first()
  await expect(dimensions.getByText('D1 信息披露质量', { exact: true })).toBeVisible()
  await expect(dimensions.getByText('D2 董事会治理有效性', { exact: true })).toBeVisible()
  await expect(dimensions.getByText('D3 内部控制与合规性', { exact: true })).toBeVisible()
  await expect(dimensions.getByText('D4 第三方声誉', { exact: true })).toBeVisible()
  const runId = new URL(page.url()).pathname.split('/').pop()
  const response = await page.request.get('/api/v1/evaluations/' + runId)
  expect(response.ok()).toBeTruthy()
  const run = (await response.json()).data
  expect(run.snapshot.summary.model_call_count).toBe(4)
  expect(run.snapshot.summary.dimensions.every(dimension => dimension.score === null)).toBeTruthy()
  expect(run.snapshot.summary.dimensions.find(dimension => dimension.code === 'D4').status).toBe('insufficient')
  await page.screenshot({ path: '../test-results/browser-four-dimensions.png', fullPage: true })
})
